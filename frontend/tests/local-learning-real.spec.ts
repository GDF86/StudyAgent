import {test,expect} from '@playwright/test'
test('显式授权：创建操作系统、上传、RAG、SSE和新库Agent',async({page})=>{
 test.skip(process.env.STUDYAGENT_REAL_LEARNING!=='AUTHORIZED','默认禁止真实调用')
 await page.route('**/*',r=>{const u=new URL(r.request().url());return u.hostname==='127.0.0.1' && ['5189','8010'].includes(u.port)?r.continue():r.abort()})
 await page.goto('/knowledge-bases')
 await page.getByRole('button',{name:'＋ 创建知识库',exact:true}).click()
 await page.getByLabel('知识库名称').fill('操作系统');await page.getByLabel('描述').fill('操作系统学习笔记，真实本机模式验证。')
 await page.getByRole('button',{name:'保存知识库'}).click()
 await expect(page.getByText('知识库已创建',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'编辑 操作系统',exact:true}).click()
 await page.getByLabel('描述').fill('进程、线程与死锁；公开自编学习资料。');await page.getByRole('button',{name:'保存知识库'}).click()
 await expect(page.getByText('知识库已更新',{exact:true})).toBeVisible()
 await page.locator('.kb-card').filter({has:page.getByRole('heading',{name:'操作系统',exact:true})}).getByRole('link',{name:'打开文档 →',exact:true}).click()
 const url=page.url();const match=url.match(/knowledge-bases\/(\d+)/);expect(match).toBeTruthy();const id=match![1]
 await expect(page.getByText(/本机真实学习模式/)).toBeVisible()
 const text='操作系统学习笔记\n\n进程是程序的一次执行。线程是CPU调度的基本单位。同一进程的线程共享地址空间。死锁产生的四个必要条件是互斥、请求并保持、不可剥夺和循环等待。本文为公开自编的简短学习资料。'
 await page.locator('#document-file').setInputFiles({name:'operating-systems-notes.txt',mimeType:'text/plain',buffer:Buffer.from(text)})
 await page.getByRole('button',{name:'上传并处理',exact:true}).click()
 await expect(page.getByText('文档已解析，文本分片和向量已保存',{exact:true})).toBeVisible({timeout:60000})
 await page.screenshot({path:'test-results/local-learning-real/01-os-upload.png',fullPage:true})
 await page.goto(`/knowledge-bases/${id}/chat`);await page.getByLabel('使用流式回答').uncheck()
 await page.getByLabel('输入问题').fill('根据上传的操作系统学习笔记，什么是进程？请引用原文。');await page.getByRole('button',{name:'发送问题'}).click()
 await expect(page.getByText('回答完成',{exact:true})).toBeVisible({timeout:60000});await expect(page.locator('.markdown-answer')).toContainText('执行')
 await page.locator('.citation-card summary').first().click()
 await page.getByLabel('使用流式回答').check();await page.getByLabel('输入问题').fill('根据上传笔记，死锁产生的四个必要条件是什么？请引用来源。');await page.getByRole('button',{name:'发送问题'}).click()
 await expect(page.getByText('回答完成',{exact:true})).toHaveCount(2,{timeout:60000});await expect(page.locator('.exchange').last()).toContainText('循环等待')
 await page.screenshot({path:'test-results/local-learning-real/02-os-rag.png',fullPage:true})
 await page.goto(`/knowledge-bases/${id}/agent`);await page.getByLabel('学习任务').fill('请使用 search_documents 工具查找操作系统笔记中的线程定义，并根据工具资料引用回答。');await page.getByRole('button',{name:'执行任务',exact:true}).click()
 await expect(page.getByRole('heading',{name:'任务完成'})).toBeVisible({timeout:60000});await expect(page.locator('[data-phase="tool_succeeded"]')).toHaveCount(1)
 await expect(page.locator('.markdown-answer')).toContainText('调度')
 await page.screenshot({path:'test-results/local-learning-real/03-os-agent.png',fullPage:true})
})
