def code(value):
    return value if isinstance(value,str) and value in REASONS else 'UNSPECIFIED'

def event(c,run_id,kind,reason,seq=None):
    c.execute('CREATE TABLE IF NOT EXISTS runtime_events (id INTEGER PRIMARY KEY,run_id TEXT NOT NULL,created REAL NOT NULL,kind TEXT NOT NULL,reason TEXT NOT NULL,seq INTEGER)')
    c.execute('INSERT INTO runtime_events(run_id,created,kind,reason,seq) VALUES (?,?,?,?,?)',(run_id,time.time(),kind if kind in KINDS else 'UNSPECIFIED',code(reason),seq))

def settled_request_boundary(ledger,before):
    """Only downgrade a UI failure when billing is entirely known and guard is READY."""
    from app.core.development_budget import risk
    from app.core.personal_learning import is_personal
    with ledger.transaction() as (c,r):
        occupied = risk(c)  # Validate bounded charges even for personal monitoring.
        if r['state']!='READY' or c.execute("SELECT 1 FROM requests WHERE status='PENDING'").fetchone() or (not is_personal(c,ledger.run_id) and occupied>=50_000_000_000):return False
        rows=c.execute('SELECT * FROM requests WHERE run_id=? ORDER BY seq LIMIT -1 OFFSET ?',(ledger.run_id,before)).fetchall()
        return all(q['status']=='SUCCESS' and q['usage_status']=='KNOWN' and
                   all(type(q[key]) is int and q[key]>=0 for key in ('cost_nano','input_tokens','output_tokens','input_bound','output_bound','reserved_nano')) and
                   q['input_tokens']<=q['input_bound'] and q['output_tokens']<=q['output_bound'] and q['cost_nano']<=q['reserved_nano'] for q in rows)


def stop_settled_application_failure(scope, error, before):
    """Opt-in Stage failure exit. Never suppress the exception or advance the stage."""
    from app.core.errors import DomainError
    from app.core.live_test import Blocked
    if (not isinstance(error, DomainError) or isinstance(error, Blocked)
            or error.code not in RECOVERABLE_AGENT_ERRORS
            or getattr(scope, 'application_error', None) != error.code):
        return False
    try:
        settled = settled_request_boundary(scope.ledger, before)
    except Blocked:
        settled = False
    if not settled:
        scope.ledger.halt('APPLICATION_ERROR_WITH_UNSETTLED_CHARGE')
        return False
    scope.ledger.record_event('REQUEST_STOPPED', error.code)
    return True
